doltlite_coverage_suites() {
  local excluded
  excluded="$(doltlite_timing_suites)"
  while IFS= read -r suite; do
    if ! grep -Fqx "$suite" <<<"$excluded"; then
      echo "$suite"
    fi
  done < <(doltlite_all_suites)
}

